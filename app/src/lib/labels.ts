export function tagLabel(tag: string, lang: Lang): string {
  if (lang === 'zh') return TAG_ZH[tag] ?? tag
  return tag
}

export function genreLabel(genre: string, lang: Lang): string {
  if (lang === 'zh') return GENRE_ZH[genre] ?? genre
  return genre
}

export function regionLabel(code: string, lang: Lang): string {
  return REGION_LABEL[code]?.[lang] ?? code
}
