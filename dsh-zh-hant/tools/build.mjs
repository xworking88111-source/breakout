/**
 * Build-time packer: convert the extracted Simplified UI dictionaries to
 * Traditional Chinese (OpenCC `twp`, Taiwan phrases) and emit `client.js`.
 *
 * Run `tools/extract.mjs` first (it writes /tmp/dsh-zh-pack.json), then this
 * script. opencc-js is a build-time dependency only; it is not shipped.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.dirname(here)
const openccDir = process.env.OPENCC_DIR ?? '/tmp/pack-tools/node_modules/opencc-js/dist/esm/full.js'
const OpenCC = await import(openccDir)
const toTW = OpenCC.Converter({ from: 'cn', to: 'twp' })

/**
 * Taiwan-preferred wording OpenCC's twp table leaves in Mainland form.
 * Applied after conversion; only unambiguous, high-frequency UI terms.
 */
const POST = [
  ['賬號', '帳號'],
  ['賬戶', '帳戶'],
  ['拖拽', '拖曳'],
  ['憑據', '憑證'],
  ['菜單', '選單'],
  ['剪貼板', '剪貼簿'],
  ['服務器', '伺服器'],
  ['內存', '記憶體'],
  ['硬盤', '硬碟'],
  ['在線', '線上'],
  ['郵箱', '信箱'],
  ['點擊', '點選'],
  ['單擊', '點選'],
  ['選項卡', '分頁'],
  ['令牌', '權杖'],
]

function localize(value) {
  let text = toTW(value)
  for (const [from, to] of POST) text = text.split(from).join(to)
  return text
}

const source = JSON.parse(fs.readFileSync('/tmp/dsh-zh-pack.json', 'utf8'))
const pack = {}
let count = 0
for (const [ns, dict] of Object.entries(source)) {
  const converted = {}
  for (const [key, value] of Object.entries(dict)) {
    const next = localize(value)
    if (next !== value) count += 1
    converted[key] = next
  }
  pack[ns] = converted
}

const packLiteral = JSON.stringify(pack)
const client = `/**
 * Traditional Chinese (zh-Hant) language pack for the DSH client.
 *
 * DSH ships only \`zh\` (Simplified) and \`en\` as baseline locales. This bundle
 * adds a \`zh-Hant\` language whose fallback is \`zh\`, then re-registers every
 * shipped UI namespace with the same keys converted to Traditional Chinese.
 * Select it in Settings → Language; the choice persists through the settings
 * document. A namespace this pack does not cover falls back to Simplified.
 *
 * Generated by tools/build.mjs from the installed package sources; do not edit
 * the PACK literal by hand.
 */
window.__ModuleLoader__.load({
  id: '@local/dsh-zh-hant',
  factory() {
    /** Locale id this pack adds. */
    const LOCALE_ID = 'zh-Hant'
    /** Namespace → Traditional dictionary. */
    const PACK = ${packLiteral}

    return {
      inject: ['locale'],
      apply(ctx) {
        ctx.effect(
          () => ctx.locale.addLanguage({ id: LOCALE_ID, label: '繁體中文', fallback: 'zh' }),
          'zh-hant: language',
        )
        for (const [ns, dict] of Object.entries(PACK)) {
          ctx.effect(() => ctx.locale.register(ns, LOCALE_ID, dict), \`zh-hant: \${ns}\`)
        }
      },
    }
  },
})
`
fs.writeFileSync(path.join(root, 'client.js'), client)
console.log(`namespaces: ${Object.keys(pack).length} | keys: ${Object.values(pack).reduce((n, d) => n + Object.keys(d).length, 0)} | changed by conversion: ${count}`)
console.log(`client.js: ${(client.length / 1024).toFixed(0)} KiB`)
